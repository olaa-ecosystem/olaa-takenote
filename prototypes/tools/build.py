#!/usr/bin/env python3
"""Build the iPad and iPhone prototypes from one source.

    python3 tools/build.py                 write shared/, ipad-home/ and iphone-home/
    python3 tools/build.py --check         exit 1 if any generated file is out of date (CI uses this)
    python3 tools/build.py --standalone D  also write one self-contained HTML file per device into D
                           [--emoji-js F]  ... with F (a script defining EMOJI) in place of the empty emoji file

Edit only source/ (and source/devices/). Everything this script writes is generated; do not edit it by hand.

  source/takenote.html          markup, shared CSS and shared JavaScript (the app)
  source/data/emoji-all.json    emoji names and categories (emoji-datasource, MIT); no images
  source/devices/devices.json   per-device settings: barScale (top bar + pen toolbar), iconScale (file icons)
  source/devices/<d>.css        device layout, loaded after the shared CSS
  source/devices/<d>.js         device settings for the app (window.OLAA_DEVICE)

Output:
  shared/css/app.css, shared/js/app.js, shared/js/emoji.js, shared/data/emoji-all.json   (shared/icons is static)
  <folder>/index.html, css/<d>.css, js/<d>.js, manifest.webmanifest, sw.js              (one folder per device)

<d>.css starts with sizes generated from the shared CSS and the device's barScale, so a change to a bar or icon size
in the shared CSS reaches every device on the next build. Standard library only. Apple emoji artwork is never written
into the repository: --emoji-js output goes to the --standalone folder, which must stay outside git.
"""
import argparse, filecmp, hashlib, json, re, shutil, sys, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'source'

# CSS rules that belong to the top bar and the pen toolbar: their sizes follow a device's barScale
BAR_TOKENS = ['#dock', '.g-dock', 'noteChip', '.tb', '.sw', '#swatches', '.minibtn', '.dgrip', 'recentTb', 'toolPill', '#topWin', '#topbar',
              '.qb', '.app ', '.app.', '.app:', '.app-', '.app{', '.apps', '.theme', '.lang ', '.lang:', '.lang{', '.lang b', '.moodBtn', '.when',
              '.vsep', '.brand', '#qTrash']
BAR_SKIP = ['appcard', '#appPop', '.app.sm', '.app.xs', '#rail', '#filesBar', '#selBar', '#railTrash', 'toolPop']

CSP = ("default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src https://fonts.gstatic.com; "
       "img-src 'self' data: blob:; connect-src 'self'; object-src 'none'; base-uri 'none'; form-action 'none'; worker-src 'self'; manifest-src 'self'")
HEAD = '/* GENERATED by tools/build.py from {src}. Do not edit: change the source and rebuild. */\n'


def parts():
    s = (SRC / 'takenote.html').read_text(encoding='utf-8')
    style = re.search(r'<style>\n(.*?)</style>', s, re.S).group(1)
    script = re.search(r'<script>\n(.*?)</script>', s, re.S).group(1)
    title = re.search(r'<title>(.*?)</title>', s).group(1)
    fonts = re.search(r'<link rel="stylesheet" href="(https://fonts\.googleapis\.com[^"]+)">', s).group(1)
    markup = s[s.index('</style>') + len('</style>'):s.index('<script>')].strip('\n')
    markup = re.sub(r'^\s*</head>\s*<body>\s*', '', markup)
    assert '/*EMOJI_DATA*/' in script, 'source script lost its /*EMOJI_DATA*/ marker'
    return style, script, title, fonts, markup


# ---- CSS: scale the bar rules for a device ----
def split_blocks(css):
    """Top-level blocks as (prelude, body); bodies of @media blocks are kept raw."""
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0: break
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == '{': depth += 1
            elif css[k] == '}': depth -= 1
            k += 1
        out.append((css[i:j].strip(), css[j + 1:k - 1]))
        i = k
    return out


def scale_px(body, f):
    def one(m):
        v = float(m.group(1))
        if abs(v) <= 1.5: return m.group(0)
        n = round(v * f, 1)
        return f"{int(n) if n == int(n) else n}px"
    decls = [d.strip() for d in re.split(r';(?=(?:[^"\']*["\'][^"\']*["\'])*[^"\']*$)(?![^()]*\))', body) if d.strip()]      # ; outside quotes and ( )
    changed = [d.split(':', 1)[0].strip() + ': ' + re.sub(r'(-?\d*\.?\d+)px', one, d.split(':', 1)[1].strip()) for d in decls
               if ':' in d and re.search(r'\d*\.?\d+px', d) and re.sub(r'(-?\d*\.?\d+)px', one, d) != d]
    return '; '.join(changed)


def bar_rules(css, f):
    if abs(f - 1) < 1e-6: return ''
    out = []
    for pre, body in split_blocks(css):
        if pre.startswith('@media') or pre.startswith('@supports'):
            inner = [f'  {p} {{ {b} }}' for p, b in ((p, scale_px(b, f)) for p, b in split_blocks(body) if is_bar(p)) if b]
            if inner: out.append(pre + ' {\n' + '\n'.join(inner) + '\n}')
        elif not pre.startswith('@') and is_bar(pre):
            b = scale_px(body, f)
            if b: out.append(f'{pre} {{ {b} }}')
    return '\n'.join(out)


def is_bar(sel):
    return any(t in sel for t in BAR_TOKENS) and not any(t in sel for t in BAR_SKIP)


def device_css(name, cfg, shared_css):
    hand = (SRC / 'devices' / f'{name}.css').read_text(encoding='utf-8')
    gen = bar_rules(shared_css, cfg['barScale'])
    out = HEAD.format(src=f'source/devices/{name}.css and devices.json')
    out += f"\n/* ---- sizes: top bar and pen toolbar at {cfg['barScale']:g} x the shared size, file icons at {cfg['iconScale']:g} ---- */\n"
    out += f".item .lift {{ scale: {cfg['iconScale']:g}; }}\n" + (gen + '\n' if gen else '')
    out += '\n/* ---- layout (source/devices/' + name + '.css) ---- */\n' + hand
    return out


# ---- the app ----
def shared_js(script):
    js = script.replace('/*EMOJI_DATA*/\n', '').replace("fetch('emoji-all.json')", "fetch('../shared/data/emoji-all.json')")
    assert "fetch('../shared/data/emoji-all.json')" in js
    js += ("\n/* installable app: work offline once opened (https or localhost only). sw.js sits in each device folder. */\n"
           "if ('serviceWorker' in navigator && (location.protocol === 'https:' || location.hostname === 'localhost' || location.hostname === '127.0.0.1')) {\n"
           "  addEventListener('load', () => navigator.serviceWorker.register('sw.js').catch(() => {}));\n}\n")
    return HEAD.format(src='source/takenote.html') + js


EMPTY_EMOJI = ("/* Emoji images. Empty on purpose: the app then draws emoji with the device's own font (Apple Color Emoji on iPad\n"
               "   and iPhone). Apple's emoji artwork is not licensed for redistribution, so it is never committed. */\nconst EMOJI = {};\n")


def index_html(name, cfg, title, fonts, markup):
    return f'''<!doctype html>
<!-- GENERATED by tools/build.py from source/takenote.html and source/devices/{name}.*. Do not edit. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">
<!-- Security: only same-origin scripts run; no inline script, no plugins, no form posts. See ipad-home/SECURITY.md. -->
<meta http-equiv="Content-Security-Policy" content="{CSP}">
<meta name="referrer" content="no-referrer">
<title>{cfg.get('title', title)}</title>
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" href="../shared/icons/icon.svg" type="image/svg+xml">
<link rel="apple-touch-icon" href="../shared/icons/icon-180.png">
<meta name="theme-color" content="#edf0ea">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="{cfg['name']}">
<meta name="apple-mobile-web-app-status-bar-style" content="default">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="{fonts}">
<link rel="stylesheet" href="../shared/css/app.css">
<link rel="stylesheet" href="css/{name}.css">
</head>
<body>
{markup}
<script src="js/{name}.js"></script>
<script src="../shared/js/emoji.js"></script>
<script src="../shared/js/app.js"></script>
</body>
</html>
'''


def manifest(cfg):
    icons = [{"src": "../shared/icons/icon-192.png", "sizes": "192x192", "type": "image/png"},
             {"src": "../shared/icons/icon-512.png", "sizes": "512x512", "type": "image/png"},
             {"src": "../shared/icons/icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
             {"src": "../shared/icons/icon.svg", "sizes": "any", "type": "image/svg+xml"}]
    return json.dumps({"name": cfg['name'], "short_name": cfg['name'], "description": cfg['description'], "id": "./", "start_url": "./",
                       "scope": "./", "display": "standalone", "orientation": cfg['orientation'], "background_color": "#edf0ea",
                       "theme_color": "#edf0ea", "lang": "en", "icons": icons}, indent=2) + '\n'


def service_worker(name, out, folder):
    files = ['./', 'index.html', f'css/{name}.css', f'js/{name}.js', 'manifest.webmanifest', '../shared/css/app.css', '../shared/js/app.js',
             '../shared/js/emoji.js', '../shared/data/emoji-all.json', '../shared/icons/icon-180.png', '../shared/icons/icon-192.png',
             '../shared/icons/icon-512.png', '../shared/icons/icon-maskable-512.png', '../shared/icons/icon.svg']
    h = hashlib.sha256()
    for f in files[1:]:
        if f != 'manifest.webmanifest': h.update((out / folder / f).resolve().read_bytes())
    v = h.hexdigest()[:12]
    return f"""/* GENERATED by tools/build.py. Offline support for the {name} build: caches the app's own files (same origin only) so it
   opens without a connection. The cache name changes with the content, so each release replaces the previous copy
   (and the single cache of the first iPad release, olaa-notes-<hash>). */
const CACHE = 'olaa-notes-{name}-{v}';
const FILES = {json.dumps(files)};
self.addEventListener('install', e => {{ e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); }});
self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE && (k.startsWith('olaa-notes-{name}-') || /^olaa-notes-[0-9a-f]{{12}}$/.test(k))).map(k => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener('fetch', e => {{
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== self.location.origin) return;      // fonts and anything else: straight to the network
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then(hit => hit || fetch(e.request).then(res => {{
    if (res.ok && res.type === 'basic') {{ const copy = res.clone(); caches.open(CACHE).then(c => c.put(e.request, copy)); }}
    return res;
  }}).catch(() => caches.match('./'))));
}});
"""


def write(p, text):
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding='utf-8')


def build(out):
    style, script, title, fonts, markup = parts()
    devices = {k: v for k, v in json.loads((SRC / 'devices' / 'devices.json').read_text()).items() if not k.startswith('_')}
    write(out / 'shared/css/app.css', HEAD.format(src='source/takenote.html') + style)
    write(out / 'shared/js/app.js', shared_js(script))
    write(out / 'shared/js/emoji.js', EMPTY_EMOJI)
    d = json.loads((SRC / 'data/emoji-all.json').read_text(encoding='utf-8'))
    write(out / 'shared/data/emoji-all.json', json.dumps({'source': d.get('source', 'emoji-datasource (MIT). Names and categories only.'), 'cats': d['cats']}, ensure_ascii=False, separators=(',', ':')))
    if out != ROOT and (ROOT / 'shared/icons').exists(): shutil.copytree(ROOT / 'shared/icons', out / 'shared/icons', dirs_exist_ok=True)
    for name, cfg in devices.items():
        f = out / cfg['folder']
        write(f / 'index.html', index_html(name, cfg, title, fonts, markup))
        write(f / f'css/{name}.css', device_css(name, cfg, style))
        write(f / f'js/{name}.js', HEAD.format(src=f'source/devices/{name}.js') + (SRC / 'devices' / f'{name}.js').read_text(encoding='utf-8'))
        write(f / 'manifest.webmanifest', manifest(cfg))
        write(f / 'sw.js', service_worker(name, out, cfg['folder']))
    return devices


GENERATED = lambda devs: ['shared/css/app.css', 'shared/js/app.js', 'shared/js/emoji.js', 'shared/data/emoji-all.json'] + [
    f"{c['folder']}/{p}" for n, c in devs.items() for p in ('index.html', f'css/{n}.css', f'js/{n}.js', 'manifest.webmanifest', 'sw.js')]


def standalone(outdir, emoji_js):
    """One self-contained file per device (for offline demos and previews). The CSP meta is dropped: inline scripts need that."""
    style, script, title, fonts, markup = parts()
    devices = {k: v for k, v in json.loads((SRC / 'devices' / 'devices.json').read_text()).items() if not k.startswith('_')}
    emoji = Path(emoji_js).read_text(encoding='utf-8') if emoji_js else EMPTY_EMOJI
    outdir = Path(outdir); outdir.mkdir(parents=True, exist_ok=True)
    if emoji_js:      # Apple emoji artwork must never reach git: only a git-ignored folder, or one outside the repository
        import subprocess
        top = subprocess.run(['git', '-C', str(ROOT), 'rev-parse', '--show-toplevel'], capture_output=True, text=True).stdout.strip()
        probe = outdir.resolve() / 'probe.apple.html'
        if top and probe.is_relative_to(Path(top).resolve()) and subprocess.run(['git', '-C', top, 'check-ignore', '-q', str(probe)]).returncode != 0:
            sys.exit(f'{outdir} is inside the repository and not git-ignored: refusing to write Apple emoji artwork there')
    for name, cfg in devices.items():
        js = script.replace('/*EMOJI_DATA*/\n', emoji + '\n')
        html = f'''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">
<title>{cfg.get('title', title)}</title><link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin><link rel="stylesheet" href="{fonts}">
<style>
{style}
{device_css(name, cfg, style)}
</style></head><body>
{markup}
<script>{(SRC / 'devices' / f'{name}.js').read_text(encoding='utf-8')}</script>
<script>
{js}</script>
</body></html>
'''
        p = outdir / f"takenote-{name}{'.apple' if emoji_js else ''}.html"
        p.write_text(html, encoding='utf-8'); print('standalone', p)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true'); ap.add_argument('--standalone'); ap.add_argument('--emoji-js')
    a = ap.parse_args()
    if a.check:
        with tempfile.TemporaryDirectory() as t:
            devs = build(Path(t)); stale = [p for p in GENERATED(devs) if not (ROOT / p).exists() or not filecmp.cmp(Path(t) / p, ROOT / p, shallow=False)]
        if stale: print('Out of date (run python3 tools/build.py):\n  ' + '\n  '.join(stale)); sys.exit(1)
        print('generated files are up to date'); return
    devs = build(ROOT); print('built', ', '.join(f"{n} -> {c['folder']}/" for n, c in devs.items()), '+ shared/')
    if a.standalone: standalone(a.standalone, a.emoji_js)


if __name__ == '__main__':
    main()
